export const supportedLanguages = ['en', 'hi', 'te'];

export const detectRegionLanguage = () => {
  const locale = navigator.language || navigator.userLanguage || 'en';
  const lowerLocale = locale.toLowerCase();
  const region = lowerLocale.split('-')[1];

  if (lowerLocale.startsWith('hi') || region === 'in') return 'hi';
  if (lowerLocale.startsWith('te')) return 'te';
  return 'en';
};

